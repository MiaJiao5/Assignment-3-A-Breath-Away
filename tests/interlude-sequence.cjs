const assert = require('node:assert/strict');
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const { translations: {en,zh} } = require('../src/i18n/translations.ts');
const { installControlledNarration } = require('./interlude-fixture.cjs');

(async()=>{
  const browser=await chromium.launch({channel:'chrome',headless:true});
  try{
    const page=await browser.newPage({viewport:{width:390,height:844}});
    const errors=[];page.on('pageerror',e=>errors.push(e.message));
    await installControlledNarration(page);
    const b=name=>page.getByRole('button',{name,exact:true});
    await page.goto(process.env.APP_URL||'http://127.0.0.1:3001');
    await b(en.INTRO_COPY.startButton).click();
    await page.waitForFunction(()=>window.__introUtterance);
    await page.waitForTimeout(1500);
    assert.equal(await page.locator('.interlude-scene').getAttribute('data-phase'),'welcome');
    assert.equal(await page.getByRole('img',{name:en.interlude.headphonesLabel}).count(),0,'No earbud icon during the first paragraph');
    assert.equal(await b(en.interlude.ready).count(),0,'Ready is inaccessible during narration');
    assert.equal(await page.locator('.interlude-ready').getAttribute('tabindex'),'-1');
    assert.equal(await page.locator('.interlude-ready').isDisabled(),true);
    assert.equal(await page.locator('.interlude-first').innerText(),en.interlude.firstLine);
    assert.equal(await page.evaluate(()=>window.__introSpoken[0].text),en.interlude.firstLine,'Fallback speaks only the welcome paragraph');
    await page.locator('.interlude-scene').click({position:{x:12,y:12}});
    assert.equal(await page.locator('main').getAttribute('data-act'),'interlude','No early blank-tap continuation');
    await page.screenshot({path:'tests/interlude-first-only.png'});
    const slot=await page.locator('.interlude-subtitles').boundingBox();
    await page.evaluate(()=>{
      window.__phaseTimes={};
      const scene=document.querySelector('.interlude-scene');
      new MutationObserver(()=>{
        const phase=scene.dataset.phase;window.__phaseTimes[phase]??=performance.now();
        const selector={fading:'.interlude-first',headphones:'.interlude-second',ready:'.interlude-ready'}[phase];
        if(selector)setTimeout(()=>{
          window.__fadeSamples??={};window.__fadeSamples[phase]=parseFloat(getComputedStyle(document.querySelector(selector)).opacity);
        },250);
      }).observe(scene,{attributes:true,attributeFilter:['data-phase']});
      window.__voiceEndedAt=performance.now();window.__finishIntro();
    });
    await page.waitForTimeout(800);
    assert.equal(await page.locator('.interlude-scene').getAttribute('data-phase'),'welcome','Full one-second pause after narration');
    await page.locator('.interlude-scene[data-phase="fading"]').waitFor();
    await page.waitForFunction(()=>window.__fadeSamples?.fading!==undefined);
    const fading=await page.evaluate(()=>window.__fadeSamples.fading);
    assert.ok(fading>0&&fading<1,'First paragraph fades out progressively');
    await page.locator('.interlude-scene[data-phase="headphones"]').waitFor();
    assert.equal(await b(en.interlude.ready).count(),0,'Ready waits for the second paragraph');
    await page.waitForFunction(()=>window.__fadeSamples?.headphones!==undefined);
    const second=await page.evaluate(()=>window.__fadeSamples.headphones);
    assert.ok(second>0&&second<1,'Headphone invitation fades into the same slot');
    assert.deepEqual(await page.locator('.interlude-subtitles').boundingBox(),slot,'Text anchor never moves');
    await page.getByRole('img',{name:en.interlude.headphonesLabel}).waitFor();
    await page.locator('.interlude-scene[data-phase="ready"]').waitFor();
    const timing=await page.evaluate(()=>({ended:window.__voiceEndedAt,...window.__phaseTimes}));
    assert.ok(timing.fading-timing.ended>=980&&timing.fading-timing.ended<1250);
    assert.ok(timing.headphones-timing.fading>=650,'First fade completes before the second begins');
    assert.ok(timing.ready-timing.headphones>=1100,'Ready starts after the second fade');
    await page.waitForFunction(()=>window.__fadeSamples?.ready!==undefined);
    const readyOpacity=await page.evaluate(()=>window.__fadeSamples.ready);
    assert.ok(readyOpacity>0&&readyOpacity<1,'Ready itself fades in');
    await page.waitForTimeout(800);
    await page.screenshot({path:'tests/interlude-earbuds-ready.png'});
    const spoken=await page.evaluate(()=>window.__introSpoken.length);
    await b('中文').click();
    assert.equal(await page.locator('.interlude-second').innerText(),zh.interlude.secondLine);
    assert.equal(await page.locator('.interlude-scene').getAttribute('data-phase'),'ready');
    assert.equal(await page.evaluate(()=>window.__introSpoken.length),spoken,'Translating stage two does not replay the first voice');
    await b(zh.interlude.ready).click();await page.locator('.quiz-scene').waitFor();
    await b(zh.back).click();await page.waitForFunction(()=>window.__introUtterance);
    const old=await page.evaluateHandle(()=>window.__introUtterance);
    await page.evaluate(()=>window.__finishIntro());
    await page.waitForTimeout(600);await b('EN').click();
    await page.waitForFunction(()=>window.__introUtterance?.lang==='en-US');
    await page.waitForTimeout(1000);
    assert.equal(await page.locator('.interlude-scene').getAttribute('data-phase'),'welcome','Changing language cancels the old transition countdown');
    assert.equal(await old.evaluate(utterance=>utterance.onend),null,'Old narration callbacks are canceled');
    await page.evaluate(()=>window.__finishIntro());await b(en.interlude.ready).waitFor();await b(en.interlude.ready).click();
    await page.locator('.quiz-scene').waitFor();await page.waitForTimeout(1200);
    assert.equal(await page.locator('main').getAttribute('data-act'),'quiz','No late timers return to the headphone stage');
    await page.close();
    const reduced=await browser.newPage({viewport:{width:320,height:568},reducedMotion:'reduce'});
    await installControlledNarration(reduced);
    await reduced.goto(process.env.APP_URL||'http://127.0.0.1:3001');
    await reduced.getByRole('button',{name:en.INTRO_COPY.startButton,exact:true}).click();await reduced.waitForFunction(()=>window.__introUtterance);
    await reduced.evaluate(()=>window.__finishIntro());await reduced.getByRole('button',{name:en.interlude.ready,exact:true}).waitFor();
    assert.equal(await reduced.locator('.headphone-icon').evaluate(el=>getComputedStyle(el).animationName),'none');
    const icon=await reduced.locator('.headphone-aura').boundingBox();
    const text=await reduced.locator('.interlude-subtitles').boundingBox();
    const ready=await reduced.locator('.interlude-ready').boundingBox();
    assert.ok(icon.y>=58 && icon.y+icon.height<text.y,'Earbuds clear the top controls on a short phone');
    assert.ok(ready.y+ready.height<=568 && text.y+text.height<ready.y,'Text and button fit without overlap');
    await reduced.screenshot({path:'tests/interlude-earbuds-320.png'});await reduced.close();
    assert.deepEqual(errors,[]);
    console.log('PASS: narration-driven two-stage text, one-second pause, fades, shared text position, delayed earbuds/Ready, canceled language timers, keyboard gating, reduced motion and 320px layout.');
  }finally{await browser.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
