const assert = require('node:assert/strict');
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const { installControlledNarration } = require('./interlude-fixture.cjs');
const { completeQuiz, approach, installNavigation } = require('./navigation.cjs');
const { translations: { en, zh } } = require('../src/i18n/translations.ts');
const { PLANETS } = require('../src/data/roamingData.ts');

(async () => {
  const browser = await chromium.launch({ channel: 'chrome', headless: true, args: ['--enable-unsafe-swiftshader'] });
  try {
    const page = await browser.newPage({ viewport: { width: 390, height: 844 }, reducedMotion: 'reduce' });
    const errors = []; page.on('pageerror', error => errors.push(error.message));
    await installControlledNarration(page);
    await page.addInitScript(() => {
      const connect = MediaElementAudioSourceNode.prototype.connect;
      MediaElementAudioSourceNode.prototype.connect = function(target, ...args) {
        if (this.mediaElement.id === 'beginning-music') window.__openingGain = target;
        return connect.call(this, target, ...args);
      };
    });
    const b = name => page.getByRole('button', { name, exact: true });
    const opening = () => page.locator('#beginning-music').evaluate(el => ({ paused: el.paused, time: el.currentTime, volume: el.volume, gain: window.__openingGain?.gain.value }));
    const finishIntro = async () => { await page.waitForFunction(() => window.__introUtterance); await page.evaluate(() => window.__finishIntro()); await b(en.interlude.ready).click(); };
    await page.goto(process.env.APP_URL || 'http://localhost:3001');
    await b(en.INTRO_COPY.startButton).click();
    assert.equal((await opening()).paused, true, 'Opening track waits for headphone confirmation');
    await finishIntro(); await page.waitForTimeout(500);
    const early = await opening();
    assert.equal(early.paused, false); assert.equal(early.volume, .7);
    assert.ok(early.gain > 0 && early.gain < .6, 'Music begins with a quiet fade');
    await page.waitForTimeout(2700);
    assert.ok((await opening()).gain > .99, 'Fade reaches its intended level');
    const beforeLanguage = await opening();
    await b('中文').click(); await b('EN').click();
    assert.ok((await opening()).time >= beforeLanguage.time, 'Language switching never restarts opening music');
    await b(en.back).click(); await page.waitForTimeout(800);
    assert.equal((await opening()).paused, true, 'Returning to narration fades and stops the opening track');
    await finishIntro(); await completeQuiz(page);
    await b(en.planetGuide.confirm).click();
    await page.waitForFunction(() => document.getElementById('beginning-music').paused);
    assert.equal((await opening()).paused, true, 'Opening music has faded out before planet exploration');
    await installNavigation(page); await approach(page, 'listening-stone', '[ Sit & Listen ]');
    await b('[ Sit & Listen ]').click(); await page.getByRole('textbox').waitFor();
    await page.waitForFunction(() => document.querySelector('.stardust-thought'));
    const freeze = () => page.evaluate(() => document.querySelectorAll('.stardust-thought').forEach(el => el.getAnimations().forEach(a => { a.pause(); a.currentTime = 9000; })));
    const rows = () => page.locator('.stardust-thought').evaluateAll(elements => elements.map(el => ({ lane: el.dataset.lane, y: el.getBoundingClientRect().y, height: el.getBoundingClientRect().height, text: el.textContent, x: el.getBoundingClientRect().x })));
    const release = async text => { await page.getByRole('textbox').fill(text); await b('[ Let It Float ]').click(); };
    await freeze(); await release('A second thought stays in its own row.'); await freeze();
    let current = await rows(); assert.equal(current.length, 2);
    const lower = current.find(row => row.lane === '1');
    await release('A new thought must not evict either visible row.');
    assert.deepEqual(await rows(), current, 'Busy tracks keep both original thoughts through their whole animation');
    const skyHeight = await page.locator('.stardust-layer').evaluate(el => el.clientHeight);
    await page.locator('.stardust-thought[data-lane="0"]').evaluate(el => el.getAnimations()[0].finish());
    await page.waitForFunction(() => document.querySelectorAll('.stardust-thought').length === 1);
    assert.equal((await rows())[0].y, lower.y, 'Lower thought never jumps up after the upper exits');
    assert.equal(await page.locator('.stardust-layer').evaluate(el => el.clientHeight), skyHeight, 'Sky reserve never collapses');
    await release('W'.repeat(60)); await freeze();
    current = await rows(); assert.equal(current.length, 2);
    assert.equal(current.find(row => row.lane === '1').y, lower.y, 'Refilling the first track does not move the second');
    const upper = current.find(row => row.lane === '0');
    assert.ok(upper.y + upper.height + 14 <= lower.y, 'Longest input fits without touching the next row');
    await b('中文').click(); await b('EN').click();
    assert.equal((await rows()).find(row => row.lane === '1').y, lower.y);
    await page.locator('.stardust-thought[data-lane="1"]').evaluate(el => el.getAnimations()[0].finish());
    await page.waitForFunction(() => document.querySelectorAll('.stardust-thought').length === 1);
    assert.equal((await rows())[0].y, upper.y, 'First row stays fixed when the second finishes');
    await page.screenshot({ path: 'tests/sky-fixed-tracks.png' });
    await page.setViewportSize({ width: 320, height: 667 }); await page.waitForTimeout(800);
    current = await rows(); const layer = await page.locator('.stardust-layer').boundingBox();
    await page.screenshot({ path: 'tests/sky-compact-tracks.png' });
    assert.ok(current[0].y + current[0].height <= layer.y + layer.height, `Long thought remains complete on a compact phone: ${JSON.stringify({current,layer})}`);
    await b('[ Stand Up ]').click(); await b(en.exitGuide.confirm).click();
    const planetBackground = await page.locator('main').evaluate(el => el.style.background);
    await b(en.ROAMING_COPY.leaveButton).click();
    await page.locator('.farewell-spirit').waitFor();
    assert.equal(await page.locator('.farewell-spirit').count(), 1);
    assert.equal(await page.locator('.farewell-spirit-body').count(), 1, 'Farewell contains one spirit body');
    assert.equal(await page.locator('main').evaluate(el => el.style.background), planetBackground, 'Leaving retains the planet-specific gradient');
    for (const [width, height] of [[320,568],[320,667],[390,844],[414,844],[1280,900]]) {
      await page.setViewportSize({ width, height });
      await page.locator('.farewell-scene').evaluate(el => { el.scrollTop = 0; });
      const mascot = await page.locator('.farewell-spirit').boundingBox();
      assert.ok(mascot.x >= 0 && mascot.x + mascot.width <= width + 1, 'Mascot stays within the frame');
      const title = await page.locator('.farewell-title').boundingBox();
      const primary = await page.locator('.farewell-primary').boundingBox();
      const secondary = await page.locator('.farewell-secondary').boundingBox();
      assert.ok(mascot.y + mascot.height <= title.y + 2, 'Mascot and text never overlap');
      assert.ok(title.y < primary.y && primary.y + primary.height <= secondary.y, 'Text and both actions retain their hierarchy');
      assert.ok(secondary.y + secondary.height <= height + 1, 'Both actions remain visible even on short phones');
      assert.equal(await page.locator('.farewell-caption').evaluate(el => getComputedStyle(el).fontFamily), await page.locator('.farewell-primary').evaluate(el => getComputedStyle(el).fontFamily), 'Small copy and controls share the application font');
      assert.equal(await page.locator('.farewell-scene').evaluate(el => getComputedStyle(el).scrollbarWidth), 'none');
      assert.equal(await page.locator('.farewell-scene').evaluate(el => getComputedStyle(el, '::-webkit-scrollbar').display), 'none');
      assert.equal(await page.locator('.farewell-spirit-wave').evaluate(el => getComputedStyle(el).animationName), 'none', 'Reduced motion removes waving');
      await page.emulateMedia({ reducedMotion: 'no-preference' });
      assert.equal(await page.locator('.farewell-spirit-wave').evaluate(el => getComputedStyle(el).animationName), 'farewellWave');
      await page.screenshot({ path: `tests/farewell-single-${width}.png` });
      await page.emulateMedia({ reducedMotion: 'reduce' });
    }
    const svg = await page.locator('.farewell-spirit svg').elementHandle();
    await b('中文').click(); await b(zh.another).waitFor();
    assert.equal(await svg.evaluate(el => el === document.querySelector('.farewell-spirit svg')), true, 'Language updates retain the SVG and animation state');
    await b('EN').click(); await page.setViewportSize({ width: 390, height: 844 });
    const visited = ['PSI_04'];
    for (let visit = 0; visit < 4; visit++) {
      const id = visited[visited.length - 1];
      const theme = await page.locator('.farewell-scene').evaluate(el => ({ cloud: el.style.getPropertyValue('--farewell-cloud'), dusk: el.style.getPropertyValue('--farewell-dusk'), light: el.style.getPropertyValue('--farewell-starlight'), background: document.querySelector('main').style.background }));
      assert.equal(theme.cloud, PLANETS[id].colors.blob2);
      assert.equal(theme.dusk, PLANETS[id].colors.blob3);
      assert.equal(theme.light, PLANETS[id].colors.planetCore);
      const expectedBackground = await page.evaluate(value => { const el = document.createElement('div'); el.style.background = value; return el.style.background; }, PLANETS[id].colors.canvasBg);
      assert.equal(theme.background, expectedBackground, `${id}: planet gradient mapping is preserved`);
      await page.screenshot({ path: `tests/farewell-nebula-${id}.png` });
      if (visit === 3) break;
      await b(en.another).click();
      if (visit < 2) await b(en.portalDiscovery.spin).click();
      await page.locator('.portal-discovery-overlay').waitFor({ state: 'hidden' });
      await installNavigation(page);
      await page.waitForFunction(() => window.__navScene.getObjectByName('interactive-garden')?.userData.pendingTextures === 0);
      const nextId = await page.evaluate(() => window.__navScene.getObjectByName('interactive-garden').userData.planetId);
      assert.ok(!visited.includes(nextId)); visited.push(nextId);
      await approach(page, 'listening-stone', '[ Sit & Listen ]');
      await b('[ Sit & Listen ]').click(); await b('[ Stand Up ]').click();
      await b(en.ROAMING_COPY.leaveButton).click(); await page.locator('.farewell-spirit').waitFor();
    }
    assert.equal(visited.length, 4);
    assert.deepEqual(errors, []);
    console.log('PASS: opening music and fixed sky tracks; single farewell SVG, all four adaptive nebula palettes and original planet gradients, mobile text/actions without overlap, shared typography, hidden scrollbars and reduced motion.');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
